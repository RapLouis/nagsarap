        <p>
            This Privacy Policy explains how <strong>Attend: Student Attendance</strong> ("4ttnd", "we", "our", or "us") collects, uses, stores, and protects personal and biometric information provided by students and authorized administrators of the College of Computing and Information Sciences (CCIS) at Mariano Marcos State University (MMSU).
        </p>

        <h2>1. Information We Collect</h2>
        <p>To verify student enrollment and prevent proxy attendance during institutional events, the application collects the following categories of data:</p>
        <ul>
            <li><strong>Account and Academic Identification:</strong> Full name (surname, first name, middle name, extension), official student number, email address, and encrypted account password.</li>
            <li><strong>Enrollment Verification Document:</strong> A PDF copy of your official Form 5 (Certificate of Registration) uploaded during account registration to confirm active student status.</li>
            <li><strong>Camera and Facial Biometric Data:</strong> A live reference selfie captured during registration and live facial verification frames captured during event check-in and check-out. These images are used strictly for liveness detection and facial identity matching.</li>
            <li><strong>Precise Location Data (Geofencing):</strong> Your device's GPS coordinates collected <em>only</em> while you actively initiate an event attendance check-in or check-out, to verify that you are within the designated event venue radius. We do not track your location continuously in the background.</li>
            <li><strong>Attendance and Device Logs:</strong> Event check-in/check-out timestamps, attendance status, sanction records, and basic offline sync diagnostics stored locally on your device and synced with our secure server.</li>
        </ul>

        <h2>2. How We Use Your Information</h2>
        <p>We process collected data solely for academic and administrative attendance management, including:</p>
        <ul>
            <li>Creating and authenticating your verified student account.</li>
            <li>Validating student enrollment via Form 5 verification.</li>
            <li>Confirming physical presence and identity at official CCIS/MMSU events through geofencing and facial liveness verification.</li>
            <li>Generating accurate attendance histories and sanction summaries for students and authorized college officers.</li>
        </ul>

        <h2>3. Data Storage, Security, and Sharing</h2>
        <ul>
            <li><strong>No Commercial Sharing:</strong> We do not sell, rent, trade, or share your personal information, facial images, location data, or Form 5 documents with advertisers or external third-party marketers.</li>
            <li><strong>Authorized Access Only:</strong> Attendance records and verification profiles are accessible only to you and authorized CCIS/MMSU administrators responsible for managing student events.</li>
            <li><strong>Security Measures:</strong> All data transmitted between the mobile application and our backend servers (<code>https://cabiebies.tech</code>) is encrypted in transit using HTTPS/TLS. Passwords are stored using secure cryptographic hashing, and access to biometric reference photos and enrollment documents is restricted by role-based authentication.</li>
            <li><strong>On-Device Processing Libraries:</strong> The app uses Google ML Kit and device camera/location APIs to detect facial landmarks and verify coordinates.</li>
        </ul>

        <h2>4. Data Retention and Account Deletion</h2>
        <p>
            Your account profile, reference photo, and attendance records are retained only for the duration of your active enrollment and academic record-keeping requirements at CCIS/MMSU.
        </p>
        <p>
            <strong>Requesting Account or Data Deletion:</strong> You may request the deletion of your account and associated personal/biometric data at any time by contacting the system administrators using the contact details below. Upon verification of your student identity, your personal profile, reference selfie, and Form 5 file will be permanently removed from active servers, except where institutional academic records must be retained by university policy.
        </p>

        <h2>5. Children's Privacy</h2>
        <p>
            This application is intended exclusively for university students and authorized faculty/officers. We do not knowingly collect personal information from children under the age of 13.
        </p>

        <h2>6. Changes to This Privacy Policy</h2>
